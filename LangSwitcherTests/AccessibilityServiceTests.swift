import XCTest
@testable import LangSwitcher

final class AccessibilityServiceTests: XCTestCase {
    
    func testEmptySelectionMarker_UTF16() {
        // Chromium stores custom clipboard data strings as UTF-16
        let json = #"{"version":1,"isFromEmptySelection":true,"multicursorText":null}"#
        let data = Data([0x01, 0x00]) + json.data(using: .utf16LittleEndian)!
        XCTAssertTrue(AccessibilityService.containsEmptySelectionMarker(data))
    }
    
    func testEmptySelectionMarker_UTF8() {
        let json = #"{"version":1,"isFromEmptySelection":true}"#
        XCTAssertTrue(AccessibilityService.containsEmptySelectionMarker(json.data(using: .utf8)!))
    }
    
    func testEmptySelectionMarker_FalseWhenSelectionWasReal() {
        let json = #"{"version":1,"isFromEmptySelection":false}"#
        XCTAssertFalse(AccessibilityService.containsEmptySelectionMarker(json.data(using: .utf16LittleEndian)!))
        XCTAssertFalse(AccessibilityService.containsEmptySelectionMarker(json.data(using: .utf8)!))
    }
    
    func testEmptySelectionMarker_FalseForPlainText() {
        XCTAssertFalse(AccessibilityService.containsEmptySelectionMarker("ghbdtn".data(using: .utf8)!))
        XCTAssertFalse(AccessibilityService.containsEmptySelectionMarker(Data()))
    }
    
    func testNormalizedForComparison_NBSPAndCRLF() {
        XCTAssertEqual(
            AccessibilityService.normalizedForComparison("ghbdtn\u{00A0}"),
            AccessibilityService.normalizedForComparison("ghbdtn ")
        )
        XCTAssertEqual(
            AccessibilityService.normalizedForComparison("a\r\nb"),
            AccessibilityService.normalizedForComparison("a\nb")
        )
    }
    
    // MARK: - Clipboard history hygiene
    // These use a private, uniquely named pasteboard — never the user's real clipboard.
    
    private var ignored: [NSPasteboard.PasteboardType] { AccessibilityService.historyIgnoredTypes }
    
    func testHistoryIgnoredTypes_AreTheStandardNSPasteboardMarkers() {
        XCTAssertEqual(
            Set(ignored.map(\.rawValue)),
            ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
        )
    }
    
    func testWriteTransientString_WritesTextAndMarkers() {
        let pb = NSPasteboard.withUniqueName()
        defer { pb.releaseGlobally() }
        
        let change = AccessibilityService.writeTransientString("привет", to: pb)
        
        XCTAssertEqual(pb.string(forType: .string), "привет")
        for type in ignored {
            XCTAssertTrue(pb.types?.contains(type) == true, "missing \(type.rawValue)")
        }
        XCTAssertEqual(change, pb.changeCount, "returned change count must be the final one")
    }
    
    func testRestore_PutsOriginalBackWithMarkers() {
        let pb = NSPasteboard.withUniqueName()
        defer { pb.releaseGlobally() }
        
        let item = NSPasteboardItem()
        item.setString("original", forType: .string)
        item.setData(Data([1, 2, 3]), forType: NSPasteboard.PasteboardType("com.example.custom"))
        
        AccessibilityService.writeTransientString("converted", to: pb)
        AccessibilityService.restore([item], to: pb)
        
        XCTAssertEqual(pb.string(forType: .string), "original")
        XCTAssertEqual(pb.data(forType: NSPasteboard.PasteboardType("com.example.custom")), Data([1, 2, 3]))
        for type in ignored {
            XCTAssertTrue(pb.types?.contains(type) == true, "missing \(type.rawValue)")
        }
    }
    
    func testRestore_EmptySnapshotLeavesPasteboardEmpty() {
        let pb = NSPasteboard.withUniqueName()
        defer { pb.releaseGlobally() }
        
        AccessibilityService.writeTransientString("converted", to: pb)
        AccessibilityService.restore([], to: pb)
        
        XCTAssertNil(pb.string(forType: .string))
    }
    
    func testMarkAsHistoryIgnored_KeepsCopiedTextAndAddsMarkers() {
        let pb = NSPasteboard.withUniqueName()
        defer { pb.releaseGlobally() }
        
        pb.clearContents()
        pb.setString("ghbdtn", forType: .string)
        AccessibilityService.markAsHistoryIgnored(pb)
        
        XCTAssertEqual(pb.string(forType: .string), "ghbdtn")
        for type in ignored {
            XCTAssertTrue(pb.types?.contains(type) == true, "missing \(type.rawValue)")
        }
    }
}
